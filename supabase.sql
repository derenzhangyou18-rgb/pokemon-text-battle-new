-- ユーザー同士のオンライン対戦用（追加）
create table if not exists public.online_battles (
  id uuid primary key default gen_random_uuid(),
  code text not null unique,
  host_id uuid not null references auth.users(id) on delete cascade,
  guest_id uuid references auth.users(id) on delete set null,
  host_team jsonb,
  guest_team jsonb,
  host_selected jsonb,
  guest_selected jsonb,
  host_action jsonb,
  guest_action jsonb,
  state jsonb,
  status text not null default 'waiting' check (status in ('waiting','selection','battle','finished')),
  turn integer not null default 1,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists online_battles_code_idx on public.online_battles(code);
create index if not exists online_battles_host_idx on public.online_battles(host_id);
create index if not exists online_battles_guest_idx on public.online_battles(guest_id);
alter table public.online_battles enable row level security;
drop policy if exists "online_battles_select_participant" on public.online_battles;
create policy "online_battles_select_participant" on public.online_battles for select to authenticated
using (host_id=auth.uid() or guest_id=auth.uid() or (status='waiting' and guest_id is null));
drop policy if exists "online_battles_insert_host" on public.online_battles;
create policy "online_battles_insert_host" on public.online_battles for insert to authenticated with check (host_id=auth.uid());
drop policy if exists "online_battles_update_participant" on public.online_battles;
create policy "online_battles_update_participant" on public.online_battles for update to authenticated using (host_id=auth.uid() or guest_id=auth.uid() or (status='waiting' and guest_id is null)) with check (host_id=auth.uid() or guest_id=auth.uid());
